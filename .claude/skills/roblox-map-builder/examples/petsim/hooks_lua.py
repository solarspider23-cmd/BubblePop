# anchors.json (written by pet_map.py) -> Hooks.lua + roblox/PuffpawHooks.lua : invisible tagged anchor parts for game scripts
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, 'anchors.json')))
def lua_attrs(a):
    return '{' + ', '.join('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else repr(v)) for k, v in a.items()) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], a['group'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a['attrs'])))
lua = '''-- PuffpawHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER PuffpawSetup.Build().
-- Makes workspace.Puffpaw.Hooks: invisible, anchored, non-colliding anchor Parts, one Folder per group. Every part gets
-- the CollectionService tag "Puffpaw_<kind>", attribute HookKind and the row's attributes.
--   spawn      SpawnLocation on the hub spawn pad (0, ~6, 70), faces north to the fountain (real SpawnLocation, Neutral)
--   station    attr Station: Fountain (billboard spot over the statue), Hatchery (over the rainbow arch), PetShop (counter),
--              Upgrades (in front of the gumball machine), Trading (trade pad trigger, 14 x 4 x 14), TradeBooth (x2)
--   board      LeaderboardFace: the BLANK board face (SurfaceGui, Face = Front; LookVector points out of the board)
--   eggstand   EggStand1..6: egg pivot on each pedestal, attrs Zone (0 hub, 1-3 zones), Egg (basic, spotted, golden,
--              meadow, candy, crystal), Index;  eggprompt = EggStand<N>_Prompt trigger box in front (ProximityPrompt)
--   gate       Gate1..3: the barrier span inside each toll arch (18 x 13 x 2), attrs ZoneIndex (the zone it unlocks), Bridge.
--              Walk-through direction = the part's +Z side leads to the bridge. Put the scripted barrier here; hide the
--              padlock mesh (ZoneGate_*) is part of the arch, recolour or leave it.
--   toll       Gate<N>_Toll: the coin podium beside the arch (ProximityPrompt "Unlock")
--   breakable  Breakable_Z<z>_<nn>: one per placed breakable prop (coin pile / gift / chest / crystal), attrs Zone, Tier (1-3),
--              Kind (kit prop name). Spawn / respawn the breakable model here; the placed props are the default look.
--   zone       Zone0..3: island bounds boxes (Zone, Name): zone membership, pet follow area, music / lighting zones
-- Row = {name, kind, group, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attrs}. Idempotent.
local CollectionService = game:GetService("CollectionService")
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("Puffpaw") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[4], r[5], r[6]) * CFrame.Angles(0, math.rad(r[7]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CastShadow = false
		p.CanQuery = r[2] ~= "station" and r[2] ~= "board" and r[2] ~= "zone"; p.CanTouch = r[2] ~= "board"
		p.Transparency = 1; p.Size = Vector3.new(r[8], r[9], r[10]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		for k, v in r[11] do p:SetAttribute(k, v) end
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0; p.CanCollide = true end
		CollectionService:AddTag(p, "Puffpaw_" .. r[2])
		local folder = f:FindFirstChild(r[3]) or Instance.new("Folder", f); folder.Name = r[3]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs(os.path.join(HERE, 'roblox'), exist_ok=True)
for p in (os.path.join(HERE, 'Hooks.lua'), os.path.join(HERE, 'roblox', 'PuffpawHooks.lua')):
    open(p, 'w').write(lua)
print(len(rows), 'hooks')
