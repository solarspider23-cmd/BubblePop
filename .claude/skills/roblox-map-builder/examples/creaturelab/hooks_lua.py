# anchors.json (written by lab_map.py) -> roblox/BloomcrestHooks.lua : invisible anchor parts for GUIs + gameplay
import json, os
d = json.load(open('anchors.json'))
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", %g, %g, %g, %g, %g, %g, %g},' % (a['name'], a['kind'], x, y, z, a['yaw'] % 360, sx, sy, sz))
lua = '''-- BloomcrestHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER BloomcrestSetup.Build().
-- Makes workspace.Bloomcrest.Hooks: invisible, anchored, non-colliding anchor Parts the game scripts bind to:
--   kind station  : station name GUI spot (Heal, Shop, Storage, Trade, Lab, Starter): a default BillboardGui is made
--   kind counter  : counter trigger box (HealCounter, ShopCounter, TradeDesk): ProximityPrompt / Touched
--   kind healslot : the 6 capsule cradles on the heal machine (put the party's capsule models here while healing)
--   kind pc       : storage terminal (screen faces LookVector): ProximityPrompt + SurfaceGui
--   kind starter  : the 3 starter capsules on the lab table (Mint, Coral, Sky)
--   kind chamber  : the Bloom Chamber pad (evolution / scan cutscene spot)
--   kind door     : the two sliding door leaves (tween them along X to open further / close)
--   kind sign     : the blank panel on the welcome monolith (SurfaceGui / BillboardGui for the centre name)
--   kind spawn    : SpawnLocation (created as a real SpawnLocation, invisible)
-- Row = {name, kind, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z}. Idempotent (replaces Hooks).
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("Bloomcrest") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[3], r[4], r[5]) * CFrame.Angles(0, math.rad(r[6]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CanQuery = r[2] ~= "station"; p.CanTouch = r[2] ~= "station"
		p.Transparency = 1; p.Size = Vector3.new(r[7], r[8], r[9]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0 end
		if r[2] == "station" then                              -- default label (replace with the game's own GUI style)
			local g = Instance.new("BillboardGui"); g.Name = "Label"; g.Size = UDim2.fromOffset(220, 56)
			g.AlwaysOnTop = false; g.MaxDistance = 160; g.LightInfluence = 0
			local t = Instance.new("TextLabel"); t.Size = UDim2.fromScale(1, 1); t.BackgroundTransparency = 1
			t.Text = r[1]; t.TextScaled = true; t.Font = Enum.Font.FredokaOne
			t.TextColor3 = Color3.new(1, 1, 1); t.TextStrokeTransparency = 0; t.Parent = g; g.Parent = p
		end
		local folder = f:FindFirstChild(r[2]) or Instance.new("Folder", f); folder.Name = r[2]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs('roblox', exist_ok=True)
open(os.path.join('roblox', 'BloomcrestHooks.lua'), 'w').write(lua); print(len(rows), 'hooks')
