# anchors.json (written by town_map.py) -> roblox/MapleJunctionHooks.lua : invisible tagged anchor parts for game scripts
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(HERE, 'anchors.json')))
def lua_attrs(a):
    return '{' + ', '.join('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else repr(v)) for k, v in a.items()) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], a['group'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a['attrs'])))
lua = '''-- MapleJunctionHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER MapleJunctionSetup.Build().
-- Makes workspace.MapleJunction.Hooks: invisible, anchored, non-colliding anchor Parts, one Folder per group. Every part
-- gets the CollectionService tag "MapleJunction_<kind>", attribute HookKind and the row's attributes.
--   spawn      SpawnLocation in the Town Square (south side), faces north to the clock tower
--   station    gameplay spots, attr Station: Shop (general store door), Cafe, Boutique, Bank (door), CarDealer
--              (showroom turntable), JobBoard (the board face: SurfaceGui / ProximityPrompt), TrainStation (platform)
--   travel     TrainTravel: platform boarding box beside the parked train (teleport / zone travel trigger)
--   traindoor  a carriage door position (cutscene / VFX)
--   prompt     extra ProximityPrompt spots (Bank_Prompt at the foot of the bank steps)
--   sign       BLANK sign faces (shop fascias, CarDealer fascia, TrainStation band): put a SurfaceGui on Face = Front;
--              the part's LookVector points out of the sign; Size = the usable panel
--   door       TownHallDoor (quest giver / interior teleport)
--   busstop    the bus shelter (bus route stop)
--   roadpath   lane centreline points: attrs Path (<Street>_<Dir>), Order, Dir, Speed (studs/s) - tween cars along them
--   roadnode   the 4 junction boxes (Streets = "West,North" ...): yield / traffic-light logic
--   npcpath    SquareWalk loop on the sidewalks round the square (attr Order)
-- Row = {name, kind, group, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attrs}. Idempotent.
local CollectionService = game:GetService("CollectionService")
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("MapleJunction") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[4], r[5], r[6]) * CFrame.Angles(0, math.rad(r[7]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CastShadow = false
		p.CanQuery = r[2] ~= "sign"; p.CanTouch = r[2] == "travel" or r[2] == "station" or r[2] == "prompt" or r[2] == "busstop"
		p.Transparency = 1; p.Size = Vector3.new(r[8], r[9], r[10]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		for k, v in r[11] do p:SetAttribute(k, v) end
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0; p.CanCollide = true; p.CanTouch = true end
		CollectionService:AddTag(p, "MapleJunction_" .. r[2])
		local folder = f:FindFirstChild(r[3]) or Instance.new("Folder", f); folder.Name = r[3]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs(os.path.join(HERE, 'roblox'), exist_ok=True)
open(os.path.join(HERE, 'roblox', 'MapleJunctionHooks.lua'), 'w').write(lua)
open(os.path.join(HERE, 'Hooks.lua'), 'w').write(lua)
print(len(rows), 'hooks')
