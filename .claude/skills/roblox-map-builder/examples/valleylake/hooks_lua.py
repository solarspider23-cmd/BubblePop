# anchors.json (written by fish_map.py) -> roblox/MistvaleLakeHooks.lua : invisible anchor parts for GUIs + gameplay
import json, os
d = json.load(open('anchors.json'))
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", %g, %g, %g, %g, %g, %g, %g},' % (a['name'], a['kind'], x, y, z, a['yaw'] % 360, sx, sy, sz))
lua = '''-- MistvaleLakeHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER MistvaleLakeSetup.Build().
-- Makes workspace.MistvaleLake.Hooks: invisible, anchored, non-colliding anchor Parts the game scripts bind to:
--   kind station   : station name GUI spot (BillboardGui goes here; nothing is written in the meshes)
--   kind fishing   : cast spot on the dock end platform - player stands here and casts outward (LookVector)
--   kind fishzone  : lake water area to cast into
--   kind waterfall : plunge-pool trigger box at the foot of the falls (secret / bonus fishing / VFX spot)
--   kind spawn     : SpawnLocation (created as a real SpawnLocation, invisible)
-- Row = {name, kind, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z}. Idempotent (replaces Hooks).
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("MistvaleLake") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[3], r[4], r[5]) * CFrame.Angles(0, math.rad(r[6]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CanQuery = r[2] ~= "station"; p.CanTouch = r[2] ~= "station"
		p.Transparency = 1; p.Size = Vector3.new(r[7], r[8], r[9]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0 end
		if r[2] == "station" then                              -- default label (replace with the game's own GUI style)
			local g = Instance.new("BillboardGui"); g.Name = "Label"; g.Size = UDim2.fromOffset(240, 60)
			g.AlwaysOnTop = false; g.MaxDistance = 220; g.LightInfluence = 0
			local t = Instance.new("TextLabel"); t.Size = UDim2.fromScale(1, 1); t.BackgroundTransparency = 1
			t.Text = r[1]:gsub("(%%l)(%%u)", "%%1 %%2"); t.TextScaled = true; t.Font = Enum.Font.FredokaOne
			t.TextColor3 = Color3.new(1, 1, 1); t.TextStrokeTransparency = 0; t.Parent = g; g.Parent = p
		end
		local folder = f:FindFirstChild(r[2]) or Instance.new("Folder", f); folder.Name = r[2]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
open(os.path.join('roblox', 'MistvaleLakeHooks.lua'), 'w').write(lua); print(len(rows), 'hooks')
