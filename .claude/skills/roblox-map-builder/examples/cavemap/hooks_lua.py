# anchors.json (written by cave_map.py) -> roblox/GlowrootCavernsHooks.lua : invisible tagged anchor parts + curated PointLights
import json, os
d = json.load(open('anchors.json'))
import cave_palette as CP
GL = {k: tuple(int(v[0][i:i + 2], 16) for i in (1, 3, 5)) for k, v in CP.GLOW.items()}
def lua_attrs(a):
    return '{' + ', '.join('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else ('true' if v is True else 'false' if v is False else repr(v))) for k, v in a.items()) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], a['group'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a['attrs'])))
for k, (x, y, z, key, w, r) in enumerate(d['lights']):           # preview watts -> Roblox range / brightness
    rng = 10 if key == 'lamp' else 14 if key in ('signal', 'fire', 'brew') else 18 if w < 5000 else 24
    br = 1.2 if key == 'lamp' else 1.6
    c = GL.get(key, (255, 255, 255))
    rows.append('\t{"Light%02d_%s", "light", "Lights", %g, %g, %g, 0, 1, 1, 1, {Color = "%d,%d,%d", Range = %d, Brightness = %g}},' % (k + 1, key, round(x, 2), round(y, 2), round(z, 2), *c, rng, br))
lua = '''-- GlowrootCavernsHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER GlowrootCavernsSetup.Build().
-- Makes workspace.GlowrootCaverns.Hooks: invisible, anchored, non-colliding anchor Parts in one Folder per group; every part
-- gets CollectionService tag "GlowrootCaverns_<kind>", attribute HookKind and the row's attributes. Nothing is in the meshes.
--   spawn       SpawnLocation on the spawn dais (Neutral), facing north at the lake, the sunbeam and the Glowroot
--   station     label spot (BillboardGui; QuestCampLabel = SurfaceGui on the board face) for MineShop, CrystalForge,
--               QuestCamp, DeepLift, BrewStation (attr Station)
--   prompt      ProximityPrompt / Touched box in front of each station (attr Station)
--   cartpath    mine-cart rail path points: attr Line (1 = spawn depot -> Ore Exchange, 2 = branch -> Crystal Forge), Order
--   cartspawn   where a cart model rests on the rails (attr Line)
--   breakable   ore / crystal nodes to mine: attr Kind (amber | cyan | violet), Tier (1 hall .. 4 lift grotto), Ore (true =
--               ore pile); the box covers the crystal cluster (use it for hit detection, respawn the cluster model on break)
--   elevator    DeepDiveTrigger = the lift cage interior (attr Destination = place / zone to teleport to, TravelTime)
--   killzone    ChasmKill (under the rope bridge), LiftShaftKill (bottom of the shaft): respawn anyone who falls in
--   sunshaft    SunShaftTop / SunShaftBottom: Beam attachments for the sunbeam (SETUP.md)
--   waterfall / water / secret / bridge   falls splash box, lake water volume (swim / fishing), Glowroot heart, chasm bridge
--   light       curated PointLights (Color / Range / Brightness attrs; Shadows off). Delete rows to trim the count.
-- Row = {name, kind, group, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attrs}. Idempotent.
local CollectionService = game:GetService("CollectionService")
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("GlowrootCaverns") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[4], r[5], r[6]) * CFrame.Angles(0, math.rad(r[7]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CastShadow = false
		p.CanQuery = r[2] ~= "station" and r[2] ~= "light"; p.CanTouch = p.CanQuery
		p.Transparency = 1; p.Size = Vector3.new(r[8], r[9], r[10]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		for k, v in r[11] do p:SetAttribute(k, v) end
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0; p.CanCollide = true end
		if r[2] == "light" then
			local c = string.split(r[11].Color, ",")
			local l = Instance.new("PointLight"); l.Color = Color3.fromRGB(tonumber(c[1]), tonumber(c[2]), tonumber(c[3]))
			l.Range = r[11].Range; l.Brightness = r[11].Brightness; l.Shadows = false; l.Parent = p
		end
		CollectionService:AddTag(p, "GlowrootCaverns_" .. r[2])
		local folder = f:FindFirstChild(r[3]) or Instance.new("Folder", f); folder.Name = r[3]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs('roblox', exist_ok=True)
open(os.path.join('roblox', 'GlowrootCavernsHooks.lua'), 'w').write(lua); print(len(rows), 'hooks')
