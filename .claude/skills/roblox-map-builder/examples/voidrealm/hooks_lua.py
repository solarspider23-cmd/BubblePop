# anchors.json (written by void_map.py) -> roblox/ShatteredVoidHooks.lua : invisible tagged anchor parts for game scripts
import json, os
d = json.load(open('anchors.json'))
def lua_attrs(a):
    return '{' + ', '.join('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else ('true' if v is True else 'false' if v is False else repr(v))) for k, v in a.items()) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], a['group'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a['attrs'])))
lua = '''-- ShatteredVoidHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER ShatteredVoidSetup.Build().
-- Makes workspace.ShatteredVoid.Hooks: invisible, anchored, non-colliding anchor Parts, one Folder per group
-- (Spawn, Stations, Paths, Lift, Starwatch, Arena, Hero). Every part gets the CollectionService tag
-- "ShatteredVoid_<kind>" and attribute HookKind (+ the row's attributes). Nothing is written in the meshes.
--   spawn       SpawnLocation (real SpawnLocation, invisible, Neutral) on the spawn dais, faces north at the singularity
--   station     name-label spot (BillboardGui / SurfaceGui): ShopSign + QuestsSign = the blank sign boards in the props
--               (SurfaceGui Face = Front); UpgradesSign / RiftGateSign / ArenaSign = billboard spots above the landmarks
--   prompt      ProximityPrompt / Touched trigger in front of each station, attr Station = Shop | Upgrades | Quests
--   portal      PortalTrigger: the rift membrane box (22 x 24 x 3), attr Destination (set it to your place / zone id)
--   lift        LiftBottom = 7 x 60 column over the spawn lift pad (attrs TargetY, Speed: apply an upward
--               LinearVelocity while inside, release at TargetY); LiftTop = landing pad on the Starwatch shard (Exit)
--   secret      HeartCrystal on the Starwatch shard (bonus / badge / reward spot)
--   arena       ArenaBounds 66 x 20 x 66 over the walled arena floor (PvP / boss zone); arenaspawn = 4 spawn points
--   bridge      one box per rune bridge deck (for zone gates / speed pads if wanted)
--   stepstone   Step01..08 tops of the floating stepping stones Altar -> Rift, attr Order
--   viewpoint   Overlook circle at the spawn promontory tip (camera / photo spot)
--   hazard      SingularityCore (44 cube round the black core: pull / damage zone; the mesh has no collision)
--   killzone    VoidKill: a 2000 x 20 x 2000 slab at y -160 - kill / respawn anyone who falls into the void
-- Row = {name, kind, group, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attrs}. Idempotent.
local CollectionService = game:GetService("CollectionService")
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("ShatteredVoid") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[4], r[5], r[6]) * CFrame.Angles(0, math.rad(r[7]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CastShadow = false
		p.CanQuery = r[2] ~= "station"; p.CanTouch = p.CanQuery
		p.Transparency = 1; p.Size = Vector3.new(r[8], r[9], r[10]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		for k, v in r[11] do p:SetAttribute(k, v) end
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0; p.CanCollide = true end
		CollectionService:AddTag(p, "ShatteredVoid_" .. r[2])
		local folder = f:FindFirstChild(r[3]) or Instance.new("Folder", f); folder.Name = r[3]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs('roblox', exist_ok=True)
open(os.path.join('roblox', 'ShatteredVoidHooks.lua'), 'w').write(lua); print(len(rows), 'hooks')
