# anchors.json (written by egg_map.py) -> roblox/EggsteadHooks.lua : invisible tagged anchor parts for the game scripts
import json, os
d = json.load(open('anchors.json'))
def lua_attrs(a):
    out = []
    for k, v in a.items():
        out.append('%s = %s' % (k, ('"%s"' % v) if isinstance(v, str) else repr(v)))
    return '{' + ', '.join(out) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], a['group'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a['attrs'])))
lua = '''-- EggsteadHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER EggsteadSetup.Build().
-- Makes workspace.Eggstead.Hooks: invisible, anchored, non-colliding anchor Parts, one Folder per group
-- (Spawn, Shops, Conveyor, Plot1..Plot8). Every part gets the CollectionService tag "Eggstead_<kind>" and attributes.
--   spawn        SpawnLocation (real SpawnLocation, invisible, Neutral), faces north up the lane
--   plot         Plot<N> bounds box (whole yard, 56 x 16 x 64), attrs PlotId, Accent: claim / ownership / steal zone
--   ownersign    blank cream face of the owner board (SurfaceGui: Face = Front; LookVector points at the lane)
--   gate         the laser / force-gate span in the yard entrance (14 x 9.6 x 1): put the scripted barrier here
--   collectpad   cash collect pad trigger (Touched)
--   eggslot      EggSlot1..10 on the nest pedestals (egg model pivot here), attrs PlotId, SlotIndex
--   coopdoor     the coop doorway (optional second checkpoint / decor spawn)
--   conveyor     ConveyorStart (eggs spawn), ConveyorEnd (last point on the belt), HatchMouth (spawn VFX spot)
--   conveyorpath Path01..Path15 points along the belt centre, attr Order (tween eggs along them, north -> south)
--   drain        DrainTrigger box at the basket drain (destroy unbought eggs)
--   shop         EggShop / Upgrades / Sell counter triggers (ProximityPrompt); shopsign = blank roof signs (GUI)
--   station      Hatchery: name / billboard spot over the hero
-- Row = {name, kind, group, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attrs}. Idempotent.
local CollectionService = game:GetService("CollectionService")
local M = {}
M.Rows = {
%s
}
function M.Build(root)
	root = root or workspace:FindFirstChild("Eggstead") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local cf = CFrame.new(r[4], r[5], r[6]) * CFrame.Angles(0, math.rad(r[7]), 0)
		local p = r[2] == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CastShadow = false
		p.CanQuery = r[2] ~= "station" and r[2] ~= "shopsign"; p.CanTouch = p.CanQuery
		p.Transparency = 1; p.Size = Vector3.new(r[8], r[9], r[10]); p.CFrame = cf
		p:SetAttribute("HookKind", r[2])
		for k, v in r[11] do p:SetAttribute(k, v) end
		if r[2] == "spawn" then p.Neutral = true; p.Duration = 0; p.CanCollide = true end
		CollectionService:AddTag(p, "Eggstead_" .. r[2])
		local folder = f:FindFirstChild(r[3]) or Instance.new("Folder", f); folder.Name = r[3]
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
os.makedirs('roblox', exist_ok=True)
open(os.path.join('roblox', 'EggsteadHooks.lua'), 'w').write(lua); print(len(rows), 'hooks')
