# anchors.json (written by dune_map.py) -> roblox/GildedDunesHooks.lua + Hooks.lua: invisible anchor parts for gameplay
import json, os
d = json.load(open('anchors.json'))
def lua_attrs(a):
    out = []
    for k, v in sorted(a.items()):
        if isinstance(v, (int, float)) and not isinstance(v, bool): out.append('%s = %s' % (k, v))
        else: out.append('%s = "%s"' % (k, str(v).replace('"', "'")))
    return '{' + ', '.join(out) + '}'
rows = []
for a in d['anchors']:
    x, y, z = a['pos']; sx, sy, sz = a['size']
    rows.append('\t{"%s", "%s", %g, %g, %g, %g, %g, %g, %g, %s},' % (a['name'], a['kind'], x, y, z, a['yaw'] % 360, sx, sy, sz, lua_attrs(a.get('attrs', {}))))
lua = '''-- GildedDunesHooks (ModuleScript, generated by hooks_lua.py from anchors.json). Run AFTER GildedDunesSetup.Build().
-- Makes workspace.GildedDunes.Hooks: invisible, anchored, non-colliding anchor Parts the game scripts bind to.
--   kind spawn   : SpawnLocation (real SpawnLocation, invisible) on the sun dais, facing -Z toward the pyramid
--   kind station : QuestStele (quests), Upgrades (sun astrolabe), CaravanTrader (shop): BillboardGui + ProximityPrompt spot
--   kind portal  : DungeonPortal, the glowing doorway at the foot of the sunken temple stair (touch / prompt -> dungeon)
--   kind dig     : DigSpot01..18, treasure mounds; attribute Tier 1 (near the city) .. 3 (far, at the ridge foot)
--   kind zone    : area trigger boxes per point of interest (attribute Poi = display name)
--   kind poi     : extra points (pyramid summit shrine, oasis well)
-- Row = {name, kind, x, y, z, yaw (deg, LookVector = -Z turned by yaw), size x, y, z, attributes}. Idempotent.
local M = {}
M.Rows = {
%s
}
local function title(s) return (s:gsub("(%%l)(%%u)", "%%1 %%2")) end
function M.Build(root)
	root = root or workspace:FindFirstChild("GildedDunes") or workspace
	local old = root:FindFirstChild("Hooks"); if old then old:Destroy() end
	local f = Instance.new("Folder"); f.Name = "Hooks"
	for _, r in M.Rows do
		local kind = r[2]
		local p = kind == "spawn" and Instance.new("SpawnLocation") or Instance.new("Part")
		p.Name = r[1]; p.Anchored = true; p.CanCollide = false; p.CanTouch = kind ~= "station"; p.CanQuery = kind ~= "zone"
		p.Transparency = 1; p.Size = Vector3.new(r[7], r[8], r[9])
		p.CFrame = CFrame.new(r[3], r[4], r[5]) * CFrame.Angles(0, math.rad(r[6]), 0)
		p:SetAttribute("HookKind", kind)
		for k, v in r[10] do p:SetAttribute(k:sub(1, 1):upper() .. k:sub(2), v) end
		if kind == "spawn" then p.Neutral = true; p.Duration = 0 end
		if kind == "station" or kind == "portal" or kind == "dig" then
			local pr = Instance.new("ProximityPrompt"); pr.Name = "Prompt"; pr.RequiresLineOfSight = false
			pr.MaxActivationDistance = kind == "dig" and 10 or 14
			pr.ActionText = r[10].prompt or (kind == "dig" and "Dig" or "Interact"); pr.ObjectText = title(r[1]); pr.Parent = p
		end
		if kind == "station" or kind == "portal" then           -- default label (swap for the game's own GUI style)
			local g = Instance.new("BillboardGui"); g.Name = "Label"; g.Size = UDim2.fromOffset(240, 60)
			g.StudsOffsetWorldSpace = Vector3.new(0, r[8] / 2 + 3, 0); g.MaxDistance = 260; g.LightInfluence = 0
			local t = Instance.new("TextLabel"); t.Size = UDim2.fromScale(1, 1); t.BackgroundTransparency = 1
			t.Text = r[10].prompt or title(r[1]); t.TextScaled = true; t.Font = Enum.Font.FredokaOne
			t.TextColor3 = Color3.fromRGB(255, 236, 170); t.TextStrokeTransparency = 0; t.Parent = g; g.Parent = p
		end
		local folder = f:FindFirstChild(kind) or Instance.new("Folder", f); folder.Name = kind
		p.Parent = folder
	end
	f.Parent = root
	return f
end
return M
''' % '\n'.join(rows)
for path in (os.path.join('roblox', 'GildedDunesHooks.lua'), 'Hooks.lua'):
    open(path, 'w', encoding='utf8').write(lua)
print(len(rows), 'hooks')
